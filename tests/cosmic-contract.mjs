import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const containerfile = await readFile(resolve(root, 'Containerfile'), 'utf8');
const smoke = await readFile(resolve(root, 'tests/smoke.sh'), 'utf8');
const installKs = await readFile(resolve(root, 'live/install.ks'), 'utf8');
const liveBuild = await readFile(resolve(root, 'live/build.sh'), 'utf8');
const liveSessionExtra = await readFile(resolve(root, 'live/livesys-session-extra'), 'utf8');
const liveTests = await readFile(resolve(root, 'tests/live.sh'), 'utf8');
const liveVm = await readFile(resolve(root, 'tests/live-vm.sh'), 'utf8');
const liveWorkflow = await readFile(resolve(root, '.github/workflows/live.yml'), 'utf8');
const channelScript = await readFile(resolve(root, '.github/scripts/channel.sh'), 'utf8');
const buildWorkflow = await readFile(resolve(root, '.github/workflows/build.yml'), 'utf8');
const bootTests = await readFile(resolve(root, 'tests/boot.sh'), 'utf8');
const pullScript = await readFile(resolve(root, '.github/scripts/pull.sh'), 'utf8');
const sigpolicy = await readFile(resolve(root, 'tests/sigpolicy.sh'), 'utf8');
const releaseWorkflow = await readFile(resolve(root, '.github/workflows/release.yml'), 'utf8');
const readme = await readFile(resolve(root, 'README.md'), 'utf8');
let manifest;
try {
  manifest = await readFile(resolve(root, 'variants/cosmic/cosmic-atomic.yaml'), 'utf8');
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
}

assert.ok(manifest, 'COSMIC package manifest is checked in');
assert.match(manifest, /49a848320cb7ce757a1d740840e756286c9c2078/, 'COSMIC package selection records its upstream manifest revision');
assert.match(containerfile, /plasma\|hyprland\|cosmic/, 'Containerfile accepts the cosmic variant');
assert.match(containerfile, /cosmic\)\s+image=agentux-cosmic/, 'COSMIC has a distinct image identity');
assert.match(containerfile, /rpm -q --quiet plasma-workspace/, 'COSMIC build rejects a Plasma base image');
assert.match(containerfile, /common="agentux-common-\$\{AGENTUX_DESKTOP_VERSION\}/, 'COSMIC installs the shared AgentUX overlay');
assert.match(containerfile, /cosmic="agentux-cosmic-\$\{AGENTUX_DESKTOP_VERSION\}/, 'COSMIC installs its own desktop overlay');
assert.match(containerfile, /^ARG AGENTUX_PLASMA_SHA256=[a-f0-9]{64}$/m, 'Plasma overlay checksum is pinned');
assert.match(containerfile, /^ARG AGENTUX_COMMON_SHA256=[a-f0-9]{64}$/m, 'shared overlay checksum is pinned');
assert.match(containerfile, /^ARG AGENTUX_COSMIC_SHA256=[a-f0-9]{64}$/m, 'COSMIC overlay checksum is pinned');
assert.match(containerfile, /printf '%s\\n' "\$packages" > \/tmp\/cosmic-packages/, 'COSMIC package manifest is materialized without a pipeline');
assert.match(containerfile, /xargs -r dnf -y install[^\n]+< \/tmp\/cosmic-packages/, 'COSMIC package names are passed without unsafe shell word splitting');
assert.match(containerfile, /if systemctl --global cat grub-boot-success\.timer/, 'build only disables the optional GRUB timer when the base provides it');
assert.match(bootTests, /agentux-cosmic[\s\S]*grub-boot-success\.timer|grub-boot-success\.timer[\s\S]*agentux-cosmic/, 'boot test accounts for COSMIC base not shipping the optional GRUB timer');
assert.match(manifest, /^  - cosmic-session$/m, 'official package set includes cosmic-session');
assert.match(manifest, /^  - cosmic-initial-setup$/m, 'official package set includes the COSMIC first-run app');
assert.doesNotMatch(manifest, /plasma|kde/i, 'COSMIC package set contains no Plasma/KDE package');
assert.match(smoke, /cosmic\) image_id=agentux-cosmic/, 'smoke test recognizes the COSMIC image ID');
assert.match(smoke, /IMAGE_ID.*agentux-cosmic.*echo cosmic/s, 'smoke test infers COSMIC when no variant is passed');
assert.match(smoke, /COSMIC session is installed/, 'smoke test checks for the COSMIC session');
assert.match(smoke, /Exec=\/usr\/bin\/start-cosmic/, 'smoke test checks the upstream COSMIC session launcher');
assert.match(installKs, /^@FIRSTBOOT_DIRECTIVE@$/m, 'install kickstart has a variant-specific firstboot slot');
assert.match(liveBuild, /firstboot --enable/, 'COSMIC live build enables Fedora Initial Setup for the installed system');
assert.match(liveBuild, /agentux-cosmic\).*AgentUX-COSMIC-Live/, 'live builder accepts and labels COSMIC');
assert.match(liveBuild, /base_profile=.*fedora-kinoite.*agentux-cosmic.*base_profile=fedora/s, 'COSMIC Anaconda profile inherits generic Fedora defaults, not Kinoite defaults');
assert.match(liveBuild, /livesys_session=cosmic/, 'COSMIC live image selects Fedora livesys COSMIC support');
assert.match(liveSessionExtra, /agentux-live-demo\.desktop/, 'COSMIC session exposes the live demo affordance');
assert.match(liveBuild, /if \[\[ "\$IMAGE_ID" != agentux-cosmic \]\]; then/, 'COSMIC live build skips Plasma-only widget setup');
assert.match(liveBuild, /agentux-cosmic.*\$\{IMAGE_ID\}/s, 'COSMIC live build derives its exact repository from image identity');
assert.match(liveTests, /agentux-cosmic/, 'live VM checks distinguish COSMIC from Plasma');
assert.match(liveTests, /cosmic-session/, 'live VM checks the COSMIC session process');
assert.match(liveTests, /LIVE_TEST_VARIANT.*usr\/lib\/os-release|usr\/lib\/os-release.*LIVE_TEST_VARIANT/s, 'live test handles both guest os-release checks and host-side install verification');
assert.match(liveTests, /agentux-cosmic.*TRACK_IMAGE|TRACK_IMAGE.*agentux-cosmic/s, 'installed COSMIC verification checks the COSMIC update target');
assert.match(liveVm, /LIVE_TEST_VARIANT.*cosmic/, 'VM test avoids Plasma-only desktop interactions for COSMIC');
assert.match(liveVm, /agentux-cosmic:latest/, 'VM test fallback tracks the COSMIC repository');
assert.match(liveVm, /qemu-img compare/, 'VM test proves the live session does not write to the install disk before install');
assert.match(liveWorkflow, /options: \[plasma, hyprland, cosmic\]/, 'manual live workflow offers COSMIC');
assert.match(liveWorkflow, /agentux-cosmic/, 'live workflow maps COSMIC to its own image repository');
assert.match(liveWorkflow, /agentux-cosmic-live/, 'COSMIC ISO has a distinct artifact prefix');
assert.match(liveWorkflow, /COSMIC.*nightly|nightly.*COSMIC/s, 'live workflow labels COSMIC as nightly-only');
assert.match(channelScript, /agentux-cosmic.*stable|stable.*agentux-cosmic/s, 'channel picker rejects stable COSMIC ISO builds');
assert.match(buildWorkflow, /node tests\/cosmic-contract\.mjs/, 'CI runs the COSMIC variant contract test');
assert.match(pullScript, /BASE_IMAGE/, 'base-image pull helper follows the parameterized Containerfile base');
assert.match(containerfile, /transports\.docker\["ghcr\.io\/agentux-os\/agentux-cosmic"\]/, 'COSMIC repository requires the AgentUX image signature');
assert.match(sigpolicy, /ghcr\.io\/agentux-os\/agentux-cosmic/, 'signature-policy tests cover signed and unsigned COSMIC images');
assert.match(buildWorkflow, /variant: cosmic[\s\S]*image: agentux-cosmic/, 'nightly image workflow maps COSMIC to its dedicated repository');
assert.match(buildWorkflow, /quay\.io\/fedora\/fedora-bootc@sha256:f2d97f1e70d557d05900d6eba9c37a29ccff9aeaf0785ba661047492cd0136bc/, 'amd64 COSMIC build uses the verified bootc digest');
assert.match(buildWorkflow, /quay\.io\/fedora\/fedora-bootc@sha256:3588110b39357b21348ab8c6e8ce7aa50c813b92a930118e06d89ca389cc0287/, 'arm64 COSMIC build uses the verified bootc digest');
assert.match(releaseWorkflow, /for pair in plasma=agentux hyprland=agentux-hyprland/, 'stable release candidate scope remains Plasma and Hyprland only');
assert.doesNotMatch(releaseWorkflow, /agentux-cosmic/, 'stable release workflow does not promote COSMIC');
assert.match(readme, /ghcr\.io\/agentux-os\/agentux-cosmic/, 'operator docs name the dedicated COSMIC image');
assert.match(readme, /COSMIC.*nightly-only|nightly-only.*COSMIC/s, 'operator docs state the COSMIC stable-release gate');
assert.match(readme, /agentux-cosmic.*sigstoreSigned|sigstoreSigned.*agentux-cosmic/s, 'operator docs explain COSMIC signature enforcement');
